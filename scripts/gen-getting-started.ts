/**
 * Writes `docs/GETTING-STARTED.md` from the guide the app shows (`src/guide/gettingStarted.ts`), so the two are one text.
 * The page adds a short opening for someone reviewing the project and one closing section the app does not show.
 * `npm run docs:getting-started` writes it; a test fails when the page on disk is not what this would write.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { GUIDE_SECTIONS, type GuideBlock } from '../src/guide/gettingStarted.ts'
import { GUIDE_TITLE } from '../src/guide/guideTitle.ts'

export const DOC_PATH = 'docs/GETTING-STARTED.md'

const OPENING = `For users: how to start with the expense tracker, from signing in to your first month. The same text is in the app, under Read the guide on the Dashboard and under Settings, Setup, Help.`

const GENERATED =
  '<!-- Generated by npm run docs:getting-started from src/guide/gettingStarted.ts. Edit that file, not this one. -->'

const LOOKING_AROUND = `## Looking around without an account

To look around without signing in, run the app on invented demo data: \`npm run dev\` (the [README](../README.md) has the setup). It is read-only. \`DOCS_CAPTURE=1 npm run dev\` lets you add and change things in memory, reset on every reload, and has the Help card with the guide under Settings, Setup.`

function block(b: GuideBlock): string {
  if (b.kind === 'p') return b.text
  if (b.kind === 'steps') return b.items.map((item, i) => `${i + 1}. ${item}`).join('\n')
  return b.items.map((item) => `- ${item}`).join('\n')
}

/** The whole page, as it should be on disk. */
export function renderGettingStarted(): string {
  const sections = GUIDE_SECTIONS.map((s) => `## ${s.title}\n\n${s.blocks.map(block).join('\n\n')}`)
  return `# ${GUIDE_TITLE}\n\n${OPENING}\n\n${[...sections, LOOKING_AROUND].join('\n\n')}\n\n${GENERATED}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = renderGettingStarted()
  let current: string | null = null
  try {
    current = readFileSync(DOC_PATH, 'utf8')
  } catch {
    // Not written yet.
  }
  if (current !== next) writeFileSync(DOC_PATH, next)
  process.stdout.write(`${current === next ? `${DOC_PATH} is up to date` : `${DOC_PATH} written`}\n`)
}
